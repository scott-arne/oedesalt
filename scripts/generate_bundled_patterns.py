#!/usr/bin/env python3
"""Generate a C++ source embedding the bundled salt/solvent SMARTS.

Reads the ``salts.smarts`` and ``solvents.smarts`` data files and writes a
``.cpp`` that defines ``OEDESALT::detail::kBundledSalts`` and
``kBundledSolvents`` as raw string literals. Run at build time by CMake so the
default patterns compile into the library and no data file is needed at runtime.
"""

import argparse
import sys
from pathlib import Path

# Raw-string delimiter. Chosen so it cannot appear in SMARTS/comment content.
_DELIM = "OEDESALT_SMARTS"


def _emit_raw_literal(text: str) -> str:
    """Wrap file content in a C++ raw string literal, guarding the delimiter.

    :param text: File contents to embed.
    :returns: A C++ raw string literal expression.
    :raises SystemExit: If the delimiter token appears in the content.
    """
    if f'){_DELIM}"' in text:
        sys.exit(
            f"error: raw-string delimiter ')({_DELIM}\"' found in embedded content; "
            "choose a different delimiter in generate_bundled_patterns.py"
        )
    return f'R"{_DELIM}(\n{text}\n){_DELIM}"'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--salts", required=True, type=Path)
    parser.add_argument("--solvents", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    salts = args.salts.read_text(encoding="utf-8")
    solvents = args.solvents.read_text(encoding="utf-8")

    body = f"""// Generated by scripts/generate_bundled_patterns.py — do not edit.
#include "oedesalt/BundledPatterns.h"

namespace OEDESALT {{
namespace detail {{

const char* const kBundledSalts = {_emit_raw_literal(salts)};

const char* const kBundledSolvents = {_emit_raw_literal(solvents)};

}}  // namespace detail
}}  // namespace OEDESALT
"""

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(body, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
